    def _calculate_trend_direction(self, theme: str, historical_data: list[dict[str, Any]]) -> str:
        """Calculate if a theme's popularity is increasing, decreasing, or stable"""
        theme_items = [item for item in historical_data if item.get("theme", "").lower() == theme.lower()]

        if len(theme_items) < 2:
            return "stable"  # Not enough data to determine trend

        # Sort by creation date
        sorted_items = sorted(theme_items, key=lambda x: x.get("created_at", ""), reverse=True)  # Most recent first

        # Compare recent activity to older activity
        recent_count = len(sorted_items[: len(sorted_items) // 3])  # Most recent third
        older_count = len(sorted_items[len(sorted_items) // 3 : len(sorted_items) * 2 // 3])  # Middle third

        if recent_count > older_count * 1.5:
            return "increasing"
        elif recent_count < older_count / 1.5:
            return "decreasing"
        else:
            return "stable"

