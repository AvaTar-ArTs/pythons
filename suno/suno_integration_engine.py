    def _analyze_evolution_pattern(self, items: list[dict[str, Any]]) -> str:
        """Analyze how content in a series evolved"""
        # Look at creation dates to understand evolution timeline
        sorted_items = sorted(items, key=lambda x: x.get("created_at", ""))

        if len(sorted_items) < 2:
            return "single_item"

        # Analyze the types of variations
        variation_types = set()
        for item in sorted_items:
            title = item.get("title", "").lower()
            if "remix" in title:
                variation_types.add("remix")
            if "remaster" in title:
                variation_types.add("remaster")
            if "live" in title:
                variation_types.add("live")
            if "acoustic" in title:
                variation_types.add("acoustic")
            if "instrumental" in title:
                variation_types.add("instrumental")

        if len(variation_types) > 2:
            return "diverse_evolution"
        elif len(variation_types) == 2:
            return "dual_evolution"
        else:
            return "sequential_evolution"

